#!/usr/bin/env python3
"""G-4: a real QLoRA SFT step on the actual 4B Brain, then a mid-epoch resume from the pushed checkpoint.

    python ops/sft_smoke.py --profile local_4050 --rows 64 --steps 4 --stop-after 2

What this gate proves, on real weights and real data:

1. ``load_for_training`` resolves the profile (4-bit nf4 on the 4050), applies LoRA to the target
   list the profile names, and reports which names the checkpoint does not have.
2. ``rtp.trainer`` runs the chunked causal-LM loss with prompt masking on GPU without materialising
   ``tokens x vocab`` logits.
3. ``run_sft`` fetches the newest checkpoint, trains, and pushes every ``--every`` steps.
4. A second call with the same arguments **resumes inside the epoch** (not at its start) and finishes
   the remaining steps.
5. Peak VRAM and wall time are recorded, because the 4050 is a 6 GB card and the plan's other
   profiles reuse these numbers.

Exit 0 only if steps were actually taken, losses are finite, the checkpoint round-tripped, and the
resumed run continued from the pushed step.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", default="local_4050")
    ap.add_argument("--stage", default="sft_gate", help="HF/local checkpoint namespace (use a new one for a clean run)")
    ap.add_argument("--rows", type=int, default=64, help="SFT rows generated by the scripted teacher")
    ap.add_argument("--steps", type=int, default=4, help="total optimizer steps to reach")
    ap.add_argument("--stop-after", type=int, default=2, help="stop the first session here")
    ap.add_argument("--every", type=int, default=1, help="push a checkpoint every N steps")
    ap.add_argument("--lr", type=float, default=1e-4)
    ap.add_argument("--max-len", type=int, default=0, help="override the profile max_len (measurement)")
    ap.add_argument("--chunk", type=int, default=0, help="override the LM-head chunk size (measurement)")
    ap.add_argument("--seed", type=int, default=100000, help="training seed (>=100000, never an eval seed)")
    ap.add_argument("--out", default="reports/sft_smoke.json")
    ap.add_argument("--no-store", action="store_true", help="local only; no HF push/fetch")
    a = ap.parse_args(argv)

    import torch

    from rtp import assetcache as ac
    from rtp.brain_train import run_sft
    from rtp.datagen import gen_brain_sft, write_jsonl
    from rtp.harness import Harness
    from rtp.profiles import get_profile, with_overrides
    from rtp.trainer import load_checkpoint

    profile = get_profile(a.profile, root=ROOT)
    if a.max_len:
        profile = with_overrides(profile, max_len=a.max_len, train_max_len=a.max_len)
    profile.ensure_dirs()
    torch.manual_seed(a.seed)

    report = {"profile": profile.name, "rows": a.rows, "steps": a.steps, "seed": a.seed,
              "max_len": profile.max_len, "train_max_len": profile.train_len,
              "stage": a.stage}
    t0 = time.time()

    harness = Harness(ROOT / "harness_files")
    rows = gen_brain_sft(a.rows, a.seed, harness)
    data = profile.paths.data / "sft_smoke.jsonl"
    write_jsonl(rows, data)
    report["dataset"] = {"path": str(data), "rows": len(rows)}
    print(f"rows: {len(rows)} -> {data}", flush=True)

    spec = ac.model_spec("Qwen/Qwen3.5-4B", revision="851bf6e8", name="qwen35-4b")
    model_dir = ac.asset_dir(spec, profile)
    problems = ac.verify_manifest(model_dir, spec)
    if problems:
        print(f"model not verified at {model_dir}: {problems[0]}")
        return 2
    report["model"] = str(model_dir)

    store = None
    if not a.no_store:
        from rtp.remotes import from_env
        try:
            store = from_env(with_kaggle=False)      # checkpoints live in HF only
        except Exception as exc:                     # noqa: BLE001
            print(f"no store ({type(exc).__name__}); running local-only")
    report["store"] = bool(store)

    # session 1: stop inside the epoch, with the checkpoint pushed
    first = run_sft(profile, model_dir=model_dir, data=data, store=store, stage=a.stage,
                    epochs=10.0, lr=a.lr, every=a.every, keep=2, seed=a.seed,
                    max_rows=a.rows, stop_after=a.stop_after,
                    chunk_tokens=a.chunk or None)
    report["session1"] = {"step": first.state.step, "epoch": first.state.epoch,
                          "micro_in_epoch": first.state.micro_in_epoch,
                          "losses": [h["loss"] for h in first.state.history],
                          "resumed_from": first.resumed_from}
    ckpt = first.out_dir / f"step-{first.state.step:09d}"
    report["checkpoint"] = {"path": str(ckpt), "exists": ckpt.exists(),
                            "state": load_checkpoint(ckpt)["state"].step if ckpt.exists() else None}

    # free the first session's tensors before loading the model again
    import gc
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    # session 2: the real resume path — fetch latest, continue, stop after a couple of steps
    longer = run_sft(profile, model_dir=model_dir, data=data, store=store, stage=a.stage,
                     epochs=10.0, lr=a.lr, every=a.every, keep=2, seed=a.seed,
                     max_rows=a.rows, stop_after=a.steps,
                     chunk_tokens=a.chunk or None)
    report["session2"] = {"step": longer.state.step, "epoch": longer.state.epoch,
                          "micro_in_epoch": longer.state.micro_in_epoch,
                          "resumed_from": longer.resumed_from,
                          "losses": [h["loss"] for h in longer.state.history][:8]}

    if torch.cuda.is_available():
        report["peak_vram_gb"] = round(torch.cuda.max_memory_allocated() / 1e9, 2)
    report["wall_s"] = round(time.time() - t0, 1)

    ok = (first.state.step >= 1 and ckpt.exists()
          and all(isinstance(x, float) and x == x for x in report["session2"]["losses"])
          and longer.state.step >= first.state.step + 1
          and (longer.resumed_from == first.state.step if store else longer.resumed_from is None))
    report["checks"] = {
        "steps_taken": first.state.step >= 1,
        "checkpoint_written": ckpt.exists(),
        "losses_finite": all(x == x for x in report["session2"]["losses"]),
        "resumed_mid_epoch": (longer.resumed_from == first.state.step) if store else None,
        "continued_past_resume_point": longer.state.step > first.state.step,
    }
    report["result"] = "PASS" if ok else "FAIL"
    report["error"] = None if ok else "see checks"

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2))
    print(f"\n-> {out}")
    print(f"{report['result']}: session1 step {first.state.step} -> session2 step {longer.state.step}, "
          f"resumed_from {longer.resumed_from}, {report.get('peak_vram_gb')} GB peak, "
          f"{report['wall_s']} s")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
