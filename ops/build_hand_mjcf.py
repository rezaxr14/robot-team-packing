#!/usr/bin/env python3
"""Derive a FR3-with-hand MJCF from the cached Menagerie FR3 v2 model.

The cached Menagerie FR3 v2 and FR3 Duo models are **arm-only**: `fr3v2_link8` is the bare flange
and there is no hand or finger body anywhere under `assets/`. A7 needs a hand, so this script writes
a derived MJCF (`assets/derived/fr3v2_hand.xml`) by inserting a simplified parallel-jaw hand into
the empty `fr3v2_link8` body of the source model and adding two position actuators with an explicit
force range. The cached source file is never modified.

Honest labelling: this is a **simplified parallel-jaw gripper** (two prismatic pads), not the Franka
Hand. A7 reports must state that the hand is this derived model, with the hash recorded here.

    python ops/build_hand_mjcf.py            # writes assets/derived/* and reports/hand_model.json

Evidence class: FIXTURE (model derivation + a load/step smoke check). No grasp or safety claim.
"""
from __future__ import annotations

import hashlib
import json
import os
import platform
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "cache" / "menagerie" / "franka_fr3_v2" / "fr3v2.xml"
OUT_DIR = ROOT / "assets" / "derived"
OUT = OUT_DIR / "fr3v2_hand.xml"
REPORT = ROOT / "reports" / "hand_model.json"

HAND_XML = """    <body name="fr3v2_link8" pos="0 0 0.107">
      <body name="hand_palm" pos="0 0 0.055">
        <inertial pos="0 0 0" mass="0.20" diaginertia="0.00040 0.00040 0.00020"/>
        <geom name="hand_palm_collision" type="box" size="0.0225 0.0300 0.009"
              friction="0.9 0.005 0.0001" rgba="0.32 0.34 0.38 1"/>
        <body name="hand_finger_left" pos="0 -0.0425 0.040">
          <joint name="hand_finger_left_joint" type="slide" axis="0 1 0" range="0 0.035"
                 damping="2" frictionloss="0.02" armature="0.001"/>
          <inertial pos="0 0 0" mass="0.04" diaginertia="0.00002 0.00002 0.00001"/>
          <geom name="hand_finger_left_pad" type="box" size="0.010 0.008 0.0225"
                friction="1.2 0.01 0.0001" rgba="0.20 0.21 0.24 1"/>
        </body>
        <body name="hand_finger_right" pos="0 0.0425 0.040">
          <joint name="hand_finger_right_joint" type="slide" axis="0 -1 0" range="0 0.035"
                 damping="2" frictionloss="0.02" armature="0.001"/>
          <inertial pos="0 0 0" mass="0.04" diaginertia="0.00002 0.00002 0.00001"/>
          <geom name="hand_finger_right_pad" type="box" size="0.010 0.008 0.0225"
                friction="1.2 0.01 0.0001" rgba="0.20 0.21 0.24 1"/>
        </body>
      </body>
    </body>"""

HAND_ACTUATORS = """    <position name="hand_finger_left" joint="hand_finger_left_joint" kp="600" kv="12"
              forcerange="-20 20" ctrlrange="0 0.035"/>
    <position name="hand_finger_right" joint="hand_finger_right_joint" kp="600" kv="12"
              forcerange="-20 20" ctrlrange="0 0.035"/>"""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def derive() -> str:
    text = SRC.read_text()
    flange = '    <body name="fr3v2_link8" pos="0 0 0.107"/>'
    if flange not in text:
        raise SystemExit(f"unexpected source: flange tag not found in {SRC}")
    compiler = '<compiler angle="radian" meshdir="assets"/>'
    if compiler not in text:
        raise SystemExit(f"unexpected source: compiler tag not found in {SRC}")
    # Stiffer, elliptic-friction contacts: the MuJoCo defaults penetrate ~4 mm at 14 N, which is
    # enough to invalidate a 1 mm penetration bound and to weaken grasps in S2/S3.
    text = text.replace(compiler, compiler + '\n  <option timestep="0.001" solref="0.001 1" '
                        'solimp="0.95 0.99 0.001" cone="elliptic" impratio="10"/>')
    text = text.replace(flange, HAND_XML)
    if "</actuator>" not in text:
        raise SystemExit(f"unexpected source: no </actuator> in {SRC}")
    text = text.replace("  </actuator>", HAND_ACTUATORS + "\n  </actuator>")
    return text


def main() -> int:
    if not SRC.exists():
        raise SystemExit(f"missing source model: {SRC}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    # The MJCF references meshes as `assets/...` relative to its own directory; link the source
    # mesh directory instead of copying ~MBs of geometry into the repo.
    link = OUT_DIR / "assets"
    target = Path("..") / "cache" / "menagerie" / "franka_fr3_v2" / "assets"
    if not link.exists():
        link.symlink_to(target, target_is_directory=True)
    text = derive()
    OUT.write_text(text)
    src_hash, out_hash = sha256(SRC), sha256(OUT)
    (OUT_DIR / "README.md").write_text(
        "# Derived models\n\n"
        "`fr3v2_hand.xml` is generated by `ops/build_hand_mjcf.py` from the cached Menagerie\n"
        "Franka Research 3 v2 model (`assets/cache/menagerie/franka_fr3_v2/fr3v2.xml`,\n"
        "Apache-2.0, see `assets/cache/menagerie/ATTRIBUTION.csv`). The cached file is never\n"
        "modified. The hand inserted at the bare flange is a **simplified parallel-jaw gripper**\n"
        "(palm box + two prismatic finger pads, +/-20 N actuator force range), not the Franka Hand.\n"
        f"\nSource sha256: `{src_hash}`\nDerived sha256: `{out_hash}`\n"
    )

    import newton
    import warp as wp

    report = {
        "step": "A7 prerequisite: derived hand model",
        "evidence_class": "FIXTURE",
        "scope": "model derivation + load/step smoke check; no grasp, contact or safety claim",
        "python": platform.python_version(),
        "source": str(SRC.relative_to(ROOT)),
        "source_sha256": src_hash,
        "derived": str(OUT.relative_to(ROOT)),
        "derived_sha256": out_hash,
        "hand": "simplified parallel-jaw gripper (not the Franka Hand)",
        "actuator_force_range_N": [-20, 20],
        "finger_travel_m": 0.035,
        "open_gap_m": 0.069,
        "checks": {},
    }
    try:
        cwd = Path.cwd()
        os.chdir(OUT.parent)
        try:
            builder = newton.ModelBuilder()
            builder.add_mjcf(OUT.name)
            model = builder.finalize()
        finally:
            os.chdir(cwd)
        labels = [lbl.split("/")[-1] for lbl in model.body_label]
        joint_labels = [lbl.split("/")[-1] for lbl in model.joint_label]
        state = model.state()
        control = model.control()
        solver = newton.solvers.SolverMuJoCo(model, njmax=256, nconmax=256)
        cp = newton.CollisionPipeline(model)
        contacts = cp.contacts()
        for _ in range(50):
            state.clear_forces()
            cp.collide(state, contacts)
            solver.step(state, state, control, contacts, 0.001)
        q = state.joint_q.numpy()
        report.update({
            "bodies": model.body_count, "shapes": model.shape_count,
            "joints": model.joint_count, "dof": model.joint_dof_count,
            "hand_bodies": [b for b in labels if b.startswith("hand_")],
            "hand_joints": [j for j in joint_labels if j.startswith("hand_")],
            "finite_after_50_steps": bool(__import__("numpy").isfinite(q).all()),
            "checks": {
                "total_dof_9_arm7_plus_2_fingers": model.joint_dof_count == 9,
                "palm_present": "hand_palm" in labels,
                "two_fingers": sum(b.startswith("hand_finger") for b in labels) == 2,
                "two_slide_joints": sum(j.startswith("hand_finger") for j in joint_labels) == 2,
                "finite_after_50_steps": bool(__import__("numpy").isfinite(q).all()),
            },
        })
        report["result"] = "PASS" if all(report["checks"].values()) else "FAIL"
    except Exception as exc:  # noqa: BLE001
        report["result"] = "FAIL"
        report["error"] = f"{type(exc).__name__}: {str(exc)[:400]}"

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: report.get(k) for k in ("result", "bodies", "dof", "hand_bodies",
                                                 "hand_joints", "checks", "error") if k in report},
                     indent=2))
    return 0 if report.get("result") == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
