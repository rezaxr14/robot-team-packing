#!/usr/bin/env python3
"""Generate real CoT traces on the symbolic harness + datagen scenes.

By default this writes N traces from ``ScriptedBrain`` (a deterministic teacher, NOT a frontier
model) to ``data/<profile>/cot_traces.jsonl`` and a status report to
``reports/cot_trace.json``. If ``RTP_SERVE_URL`` is configured and ``--frontier`` is passed, it
instead asks that OpenAI-compatible endpoint for a real completion; failures are recorded in the
trace file and fall back to a scripted trace.

Nothing here fabricates a model answer: the report always states which source produced each trace.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from rtp import frontier_cot as fc  # noqa: E402
from rtp.datagen import default_eyes, sample_spec, sample_world  # noqa: E402
from rtp.harness import Harness  # noqa: E402
from rtp.perception import merge_scenes  # noqa: E402
from rtp.profiles import get_profile  # noqa: E402


def _parse_args(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, default=6, help="number of scenes/traces (default: 6)")
    ap.add_argument("--profile", default=None, help="rtp profile (default: $RTP_PROFILE or local_4050)")
    ap.add_argument("--seed0", type=int, default=0, help="first datagen seed (default: 0)")
    ap.add_argument("--k", type=int, default=6, help="retrieval budget per pass (default: 6)")
    ap.add_argument("--style", choices=sorted(fc.STYLES), default="brief")
    ap.add_argument("--frontier", action="store_true",
                    help="if RTP_SERVE_URL is configured, call it for real (else still scripted)")
    ap.add_argument("--out", default=None, help="override trace JSONL path")
    ap.add_argument("--report", default=None, help="override report JSON path")
    args = ap.parse_args(argv)
    if args.n < 1:
        ap.error("--n must be >= 1")
    if args.k < 1:
        ap.error("--k must be >= 1")
    return args


def main(argv=None) -> int:
    args = _parse_args(argv)
    prof = get_profile(args.profile)
    prof.ensure_dirs()
    harness = Harness(str(ROOT / "harness_files"))
    out = Path(args.out) if args.out else prof.paths.data / "cot_traces.jsonl"
    report_path = Path(args.report) if args.report else ROOT / "reports" / "cot_trace.json"

    status, model = fc.frontier_status()
    use_frontier = bool(args.frontier and status == "configured")
    if args.frontier and not use_frontier:
        print(f"SKIPPED: frontier requested but unavailable ({status}); using scripted teacher")

    records, frontier_attempts, frontier_errors = [], 0, 0
    for seed in range(args.seed0, args.seed0 + args.n):
        world = sample_world(seed)
        spec = sample_spec(world, seed)
        scene = merge_scenes([e.report(world, 0) for e in default_eyes(seed)])
        if use_frontier:
            frontier_attempts += 1
            rec = fc.run_cot(harness, spec, scene, k=args.k, style=args.style, seed=seed)
            if rec["error"]:
                frontier_errors += 1
                print(f"frontier seed {seed} failed: {rec['error']} -- falling back to scripted")
            else:
                records.append(rec)
                continue
        records.append(fc.scripted_cot(harness, spec, scene, k=args.k, style=args.style, seed=seed))

    fc.write_traces(records, out)
    by_source = dict(Counter(r["source"] for r in records))
    frontier_ok = by_source.get(fc.FRONTIER_SOURCE, 0)
    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "profile": prof.name,
        "n_requested": args.n,
        "counts": {"total": len(records), "by_source": by_source},
        "sources": sorted(by_source),
        "frontier_status": status,
        "frontier_model": model if use_frontier else None,
        "frontier_attempts": frontier_attempts,
        "frontier_errors": frontier_errors,
        "frontier_traces": frontier_ok,
        "trace_path": str(out),
        "style": args.style,
        "seed_range": [args.seed0, args.seed0 + args.n - 1],
        "note": (
            "Frontier completions were generated by the configured endpoint."
            if frontier_ok else
            "No frontier model was run. All traces come from ScriptedBrain, a deterministic "
            "teacher/fixture on real harness retrieval and datagen scenes; they are not LLM evidence."
        ),
    }
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2) + "\n")

    print(f"traces: {len(records)} -> {out}")
    print("by source:", by_source)
    print("frontier_status:", status)
    print("report:", report_path)
    if records:
        ex = records[0]
        print("--- example trace (truncated) ---")
        print("source:", ex["source"], "| seed:", ex["seed"], "| doc ids:", ex["retrieved_doc_ids"][:6])
        print("prompt[:400]:", ex["prompt"][:400].replace("\n", " ⏎ "))
        print("completion[:400]:", ex["completion"][:400].replace("\n", " ⏎ "))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
