#!/usr/bin/env python3
"""Generate ops/kaggle/g3_t4/g3_t4.py: a Kaggle T4 kernel that runs the Newton G-3 gate.

The laptop already has G-3 PASS on an RTX 4050; this kernel records the T4 half. Nothing runs here.
Kaggle downloads and installs Isaac Lab 3.0.0 from the tag's own uv.lock (the same recipe as
ops/install.sh --isaac), runs the unmodified ops/g3_sim.py embedded in the kernel, and writes
g3_sim_t4.json + PNGs into /kaggle/working so `kaggle kernels output` can fetch them.

No Kaggle secret is needed: the kernel only needs internet and a GPU, and its output is downloaded
with the owner's local credentials.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GATE = (ROOT / "ops" / "g3_sim.py").read_text()
DEST = ROOT / "ops" / "kaggle" / "g3_t4" / "g3_t4.py"

WRAPPER = '''#!/usr/bin/env python3
"""Kaggle T4 half of gate G-3 (generated by ops/kaggle/build_g3_kernel.py — do not edit here).

Internet + GPU enabled. Installs Isaac Lab v3.0.0 with the tag's uv.lock (no Isaac Sim/PhysX),
then runs the embedded, unmodified ops/g3_sim.py and writes its JSON/PNG evidence to /kaggle/working.
"""
import json
import os
import subprocess
import sys
from pathlib import Path

TEMP = Path("/kaggle/temp")
WORK = Path("/kaggle/working") if Path("/kaggle/working").is_dir() else Path.cwd()
REPO = TEMP / "IsaacLab"
VENV = TEMP / "venvs" / "isaac_newton"
GATE = TEMP / "g3_sim.py"
OUT = WORK / "g3_sim_t4.json"
IMAGES = WORK / "g3_images"


def run(*args, **kw):
    print("+", " ".join(str(a) for a in args), flush=True)
    return subprocess.run([str(a) for a in args], check=True, text=True, capture_output=True, **kw)


def main():
    TEMP.mkdir(parents=True, exist_ok=True)
    print("GPU:", run("nvidia-smi", "--query-gpu=name,memory.total,compute_cap", "--format=csv,noheader").stdout.strip(), flush=True)
    run(sys.executable, "-m", "pip", "install", "-q", "uv")
    if not (REPO / ".git").is_dir():
        run("git", "clone", "--depth", "1", "--branch", "v3.0.0",
            "https://github.com/isaac-sim/IsaacLab.git", REPO)
    else:
        run("git", "-C", REPO, "checkout", "v3.0.0")
    env = {**os.environ, "UV_PROJECT_ENVIRONMENT": str(VENV)}
    run("uv", "sync", "--project", REPO, "--no-dev", env=env)
    GATE.write_text(__GATE_SOURCE__)
    py = VENV / "bin" / "python"
    print("Isaac python:", py, flush=True)
    result = subprocess.run([str(py), str(GATE), "--out", str(OUT), "--images", str(IMAGES)],
                            text=True, capture_output=True)
    print(result.stdout[-4000:], flush=True)
    print(result.stderr[-2000:], flush=True)
    if OUT.exists():
        report = json.loads(OUT.read_text())
        print("G-3 T4 result:", report.get("result"), "| versions:", report.get("versions"),
              "| checks:", report.get("checks"), flush=True)
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
'''

DEST.parent.mkdir(parents=True, exist_ok=True)
DEST.write_text(WRAPPER.replace("__GATE_SOURCE__", repr(GATE)))
print("wrote", DEST)
