#!/usr/bin/env python3
"""Generate the hosted Kaggle task for multi-turn frontier episodes (data generation and benchmark rows).

The hosted worker is 4 CPU / no GPU / no torch (KAGGLE_SKILL.md section 6), has git + pip, and receives the Model
Proxy URL/key from the platform. The generated ``task.py`` therefore clones this repo (default branch: PUSH FIRST),
installs numpy only, and runs ``rtp.datagen_run.run_shard`` for ONE model (hosted runs are one model per run).
Episodes run on the CPU pose-level environment from ``rtp.benchmark.make_cases``; image views from the Newton
renderer are a later stage (docs/DATAGEN_KAGGLE.md). The current success/failure memory notes are embedded in the
spec (small, no secrets).

    python ops/kaggle/multiturn/build_task.py --seeds 100000:100010 --condition harness --mode datagen \
        --iteration 0 --shard haiku-it0-s0 [--memory runs/memory_it0.json] [--repo-url URL]
    kaggle benchmarks tasks push rtp-multiturn-<shard> -f ops/kaggle/multiturn/task.py
    kaggle benchmarks tasks run  rtp-multiturn-<shard> -m claude-haiku-5-5
    kaggle benchmarks tasks download rtp-multiturn-<shard> -o OUT -m claude-haiku-5-5 -s -f
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DEST = ROOT / "ops" / "kaggle" / "multiturn" / "task.py"
DEFAULT_REPO = "https://github.com/rezaxr14/robot-team-packing.git"

TASK_TEMPLATE = '''#!/usr/bin/env python3
"""Hosted Kaggle Benchmarks multi-turn task (generated by build_task.py -- do not edit here)."""
# No `from __future__ import annotations`: kbench matches the type object of the return annotation.
import json
import os
import subprocess
import sys
from pathlib import Path

import kaggle_benchmarks as kbench

SPEC = json.loads(__SPEC_JSON__)
WORK = Path("/kaggle/working")


def _sh(cmd, steps):
    p = subprocess.run(cmd, capture_output=True, text=True)
    steps.append({"cmd": " ".join(cmd[:3]), "rc": p.returncode, "tail": (p.stdout + p.stderr)[-300:]})
    return p.returncode == 0


def prepare(repo_dir=None, work=WORK):
    """clone (default branch) + numpy; returns (repo_path, steps)."""
    steps = []
    if repo_dir is None:
        repo_dir = WORK / "rtp_repo"
        if not repo_dir.exists() and not _sh(["git", "clone", "--depth", "1", SPEC["repo_url"], str(repo_dir)], steps):
            raise RuntimeError("git clone failed: " + json.dumps(steps))
    try:
        import numpy  # noqa: F401
    except ImportError:
        _sh([sys.executable, "-m", "pip", "install", "-q", "numpy"], steps)
    sys.path.insert(0, str(repo_dir))
    return Path(repo_dir), steps


def execute(model, url, api_key, *, repo_dir=None, work=WORK, post=None, harness_tmp=str(WORK / "rtp_harness")):
    import shutil
    repo, steps = prepare(repo_dir, work)
    from rtp.datagen_memory import write_memory_docs
    from rtp.datagen_run import run_shard
    from rtp.kaggle_chat import ProxyTransport
    sha = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    hroot = Path(harness_tmp)
    if hroot.exists():
        shutil.rmtree(hroot)
    shutil.copytree(repo / "harness_files", hroot)
    if SPEC["memory_notes"]:
        write_memory_docs(SPEC["memory_notes"], hroot, SPEC["iteration"])
    transport = ProxyTransport(model, url=url, api_key=api_key, max_tokens=SPEC["max_tokens"], post=post)
    out = Path(work) / "multiturn" / SPEC["shard"]
    seeds = list(range(SPEC["seed_start"], SPEC["seed_stop"]))
    manifest = run_shard(seeds=seeds, transport=transport, harness_root=hroot, out_dir=out, condition=SPEC["condition"],
                         mode=SPEC["mode"], max_turns=SPEC["max_turns"], shard=SPEC["shard"], iteration=SPEC["iteration"],
                         model_label=model, sleep=__import__("time").sleep, arm_model=SPEC["arm_model"])
    manifest.update({"repo_sha": sha, "repo_url": SPEC["repo_url"], "spec_hash": SPEC["spec_hash"], "setup_steps": steps,
                     "memory_notes": len(SPEC["memory_notes"]), "api": "POST /openapi/chat/completions (OpenAI-compatible Model Proxy)"})
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\\n", encoding="utf-8")
    return manifest


@kbench.task(name=__TASK_NAME__, description="Multi-turn frontier episodes on the RTP harness")
def rtp_multiturn(llm) -> dict:
    base = os.environ["MODEL_PROXY_URL"].rstrip("/")
    if not base.endswith("/openapi"):
        base += "/openapi"
    return execute(llm.model, base + "/chat/completions", os.environ["MODEL_PROXY_API_KEY"])


rtp_multiturn.run(kbench.llm)
'''


def build(*, seeds: str, condition: str, mode: str, iteration: int, shard: str, memory_notes: list,
          max_turns: int = 8, max_tokens: int = 1200, repo_url: str = DEFAULT_REPO, dest: Path = DEST,
          arm_model: str = "sim_pose_v0") -> dict:
    a, b = (int(x) for x in seeds.split(":"))
    if mode == "datagen" and a < 100000:
        raise SystemExit("datagen seeds must be >= 100000 (held-out namespace is < 100000)")
    if mode == "eval" and b > 100000:
        raise SystemExit("eval seeds must be < 100000")
    spec = {"task_name": f"rtp-multiturn-{shard}", "repo_url": repo_url, "seed_start": a, "seed_stop": b,
            "condition": condition, "mode": mode, "iteration": iteration, "shard": shard, "max_turns": max_turns,
            "max_tokens": max_tokens, "memory_notes": memory_notes, "arm_model": arm_model}
    spec["spec_hash"] = hashlib.sha256(json.dumps(spec, sort_keys=True).encode()).hexdigest()[:16]
    dest.write_text(TASK_TEMPLATE.replace("__SPEC_JSON__", repr(json.dumps(spec, ensure_ascii=False)))
                    .replace("__TASK_NAME__", repr(spec["task_name"])), encoding="utf-8")
    return spec


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", required=True, help="start:stop (stop exclusive)")
    ap.add_argument("--condition", choices=("harness", "zero_shot"), default="harness")
    ap.add_argument("--mode", choices=("datagen", "eval"), default="datagen")
    ap.add_argument("--iteration", type=int, default=0)
    ap.add_argument("--shard", required=True)
    ap.add_argument("--memory", help="JSON file with a list of memory notes (rtp.datagen_memory.notes_from_records)")
    ap.add_argument("--max-turns", type=int, default=8)
    ap.add_argument("--max-tokens", type=int, default=1200)
    ap.add_argument("--arm-model", default="sim_pose_v0", help="arm-outcome model id; SFT accepts only certified tables")
    ap.add_argument("--repo-url", default=DEFAULT_REPO)
    a = ap.parse_args()
    notes = json.loads(Path(a.memory).read_text()) if a.memory else []
    spec = build(seeds=a.seeds, condition=a.condition, mode=a.mode, iteration=a.iteration, shard=a.shard,
                 memory_notes=notes, max_turns=a.max_turns, max_tokens=a.max_tokens, repo_url=a.repo_url, arm_model=a.arm_model)
    print(f"wrote {DEST}  task={spec['task_name']}  spec_hash={spec['spec_hash']}  notes={len(notes)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
