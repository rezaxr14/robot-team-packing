#!/usr/bin/env python3
"""Generate ops/kaggle/cot_frontier/task.py from the real harness prompt JSONL.

The generated file is a Kaggle Benchmarks *hosted task*: the worker gets the Model Proxy URL/key
injected by the platform (Kaggle Secrets do not work there), calls a frontier model via the exact
OpenAI-compatible /openapi/chat/completions route, and writes verbatim transport records plus a
small manifest to /kaggle/working. No completion is fabricated; failures keep an error string.

    $V/bin/python ops/cot_prompts.py
    $V/bin/python ops/kaggle/cot_frontier/build_task.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from ops.cot_prompts import REQUIRED_FIELDS, read_records  # noqa: E402

DEFAULT_PROMPTS = ROOT / "data" / "local_4050" / "cot_prompts.jsonl"
DEST = ROOT / "ops" / "kaggle" / "cot_frontier" / "task.py"
TASK_NAME = "rtp-cot-frontier-fullplan"
SOURCE_LABEL = "kaggle-benchmarks-proxy"
MAX_TOKENS = 1200

# __SPEC_JSON__ is replaced with repr(json.dumps(spec)) at build time (same pattern as g3).
TASK_TEMPLATE = '''#!/usr/bin/env python3
"""Hosted Kaggle Benchmarks CoT task (generated by build_task.py -- do not edit here).

Calls the frontier model attached to this run through Kaggle's Model Proxy and writes
/kaggle/working/cot_frontier_traces.jsonl + cot_frontier_manifest.json. No invented answers.
"""
# No `from __future__ import annotations`: kbench matches the *type object* of the return
# annotation against its registry, and a postponed string annotation is rejected on the worker.
import json
import os
import subprocess
import sys
import time
from pathlib import Path

import kaggle_benchmarks as kbench

try:
    import requests
except ImportError:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "requests"], check=True)
    import requests

SPEC = json.loads(__SPEC_JSON__)
WORK = Path("/kaggle/working")
TRACES = WORK / "cot_frontier_traces.jsonl"
MANIFEST = WORK / "cot_frontier_manifest.json"


def endpoint():
    """Inside a hosted run MODEL_PROXY_URL already ends in /openapi."""
    base = os.environ["MODEL_PROXY_URL"].rstrip("/")
    if not base.endswith("/openapi"):
        base += "/openapi"
    return base + "/chat/completions"


def call_model(url, model, prompt):
    # Hidden reasoning consumed the whole budget on the first run: ask for reasoning off so the
    # visible Reasoning + Plan JSON is actually emitted. Learn from a 400 if this model disagrees.
    payload = {"model": model, "max_tokens": SPEC["max_tokens"], "temperature": 0,
               "reasoning_effort": "none",
               "messages": [{"role": "user", "content": prompt}]}
    headers = {"Authorization": "Bearer " + os.environ["MODEL_PROXY_API_KEY"]}

    def post():
        t0 = time.perf_counter()
        r = requests.post(url, headers=headers, json=payload, timeout=300)
        return r, round(time.perf_counter() - t0, 3)

    response, latency = post()
    if response.status_code != 200:
        lowered = response.text.lower()
        changed = False
        if response.status_code == 400 and "reasoning_effort" in lowered:
            payload.pop("reasoning_effort", None)
            changed = True
        if response.status_code == 400 and "max_completion_tokens" in lowered and "max_tokens" in payload:
            payload["max_completion_tokens"] = payload.pop("max_tokens")
            changed = True
        if changed:
            response, latency = post()
        if response.status_code != 200:
            raise RuntimeError("HTTP " + str(response.status_code) + ": " + response.text[:500])
    data = response.json()
    choice = data["choices"][0]
    return {"completion": choice["message"].get("content") or "",
            "finish_reason": choice.get("finish_reason"), "usage": data.get("usage"),
            "response_model": data.get("model"), "latency_s": latency,
            "request_params": {"model": payload["model"], "max_tokens": payload.get("max_tokens"),
                               "max_completion_tokens": payload.get("max_completion_tokens"),
                               "temperature": payload.get("temperature"),
                               "reasoning_effort": payload.get("reasoning_effort")}}


@kbench.task(name=SPEC["task_name"], description="Real Kaggle-hosted frontier CoT on harness prompts")
def rtp_cot_frontier_fullplan(llm) -> dict:
    WORK.mkdir(parents=True, exist_ok=True)
    TRACES.write_text("", encoding="utf-8")
    model = llm.model                       # provider-prefixed slug, e.g. google/gemini-3-flash-preview
    url = endpoint()
    errors, records = [], []
    try:
        for row in SPEC["prompts"]:
            rec = {"id": row["id"], "seed": row["seed"], "prompt": row["prompt"],
                   "retrieved_ids": row["retrieved_ids"], "task_class": row["task_class"],
                   "source": SPEC["source"], "model": model, "completion": "",
                   "latency_s": 0.0, "finish_reason": None, "usage": None, "error": None}
            try:
                result = call_model(url, model, row["prompt"])
                rec.update(result)
            except Exception as exc:
                rec["error"] = type(exc).__name__ + ": " + str(exc)
                errors.append({"id": row["id"], "error": rec["error"]})
            records.append(rec)
            with TRACES.open("a", encoding="utf-8") as f:
                f.write(json.dumps(rec, ensure_ascii=False) + "\\n")
    except Exception as exc:
        errors.append({"id": "task", "error": type(exc).__name__ + ": " + str(exc)})
    manifest = {"status": "ok" if not errors else "partial", "model": model,
                "endpoint": url, "api": "POST /openapi/chat/completions (OpenAI-compatible Model Proxy)",
                "source": SPEC["source"], "count": len(records),
                "completed": sum(1 for r in records if r["completion"] and not r["error"]),
                "errors": errors, "finish_reasons": [r["finish_reason"] for r in records],
                "request_params": (records[0].get("request_params") if records else
                                   {"model": model, "max_tokens": SPEC["max_tokens"],
                                    "reasoning_effort": "none"}),
                "total_usage": {k: sum(r["usage"][k] for r in records if isinstance(r.get("usage"), dict)
                                       and isinstance(r["usage"].get(k), (int, float)))
                                for k in ("prompt_tokens", "completion_tokens")}}
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\\n", encoding="utf-8")
    return manifest


rtp_cot_frontier_fullplan.run(kbench.llm)
'''


def load_prompt_records(path: Path | str = DEFAULT_PROMPTS) -> list[dict]:
    rows = read_records(path)
    if not rows:
        raise FileNotFoundError(f"no prompt records in {path}; run ops/cot_prompts.py first")
    for i, row in enumerate(rows):
        missing = [k for k in REQUIRED_FIELDS if k not in row]
        if missing:
            raise ValueError(f"{path}:{i + 1} missing {missing}")
    return rows


def build_task_source(records: list[dict], *, task_name: str = TASK_NAME,
                      max_tokens: int = MAX_TOKENS) -> str:
    spec = {"task_name": task_name, "source": SOURCE_LABEL, "max_tokens": max_tokens,
            "prompts": [{k: r[k] for k in REQUIRED_FIELDS} for r in records]}
    return TASK_TEMPLATE.replace("__SPEC_JSON__", repr(json.dumps(spec, ensure_ascii=False)))


def main(argv=None) -> int:
    rows = load_prompt_records()
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(build_task_source(rows), encoding="utf-8")
    print(json.dumps({"task_name": TASK_NAME, "prompts": len(rows), "file": str(DEST)}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
